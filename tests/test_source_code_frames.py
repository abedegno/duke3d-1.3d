class SourceCodeFrameTests(unittest.TestCase):
 def fixture(self,loader=None):
  raw=bytearray(fixture() if loader is None else with_fixups(loader))
  # Source contribution begins at4; target24 lies elsewhere in the same object.
  raw[0x444:0x44a]=b'\xe8\x0f\0\0\0\xc3'
  image=LEImage.parse(bytes(raw))
  m=Module(segments=[Segment('_TEXT','CODE',6,0xa9,bytearray(b'\xe8\0\0\0\0\xc3'))],
      publics={'caller_':(1,0)},externals=['callee_'],fixups=[Fixup(1,1,4,9,True,0,1,2,1,0)])
  return m,image
 def check(self,m,image,symbols=None,placements=None):
  return compare_range(m,1,0,image,1,4,6,{'callee_':(1,24)} if symbols is None else symbols,placements)
 def test_measured_source_frame_relative_external_at_nonzero_placement(self):
  m,image=self.fixture();r=self.check(m,image)
  self.assertTrue(r['match']);self.assertEqual(r['compared_bytes'],6);self.assertEqual(r['verified_fixups'],1)
 def test_each_unmeasured_frame_role_remains_rejected(self):
  cases=[{'frame':None},{'frame':0},{'frame':2},{'frame_method':2,'frame':2},{'relative':False},
         {'width':2},{'location':1},{'target_method':1},{'target_method':0,'target':2},
         {'displacement':1},{'displacement':-1},{'target':0},{'target':2}]
  for values in cases:
   m,image=self.fixture();m.fixups[0]=replace(m.fixups[0],**values)
   with self.subTest(values=values),self.assertRaises(MatchError):self.check(m,image)
 def test_use16_noncode_and_easy_are_not_new_cases(self):
  for kind in ['use16','data','easy']:
   m,image=self.fixture()
   if kind=='use16':m.segments[0].attributes &= ~1
   elif kind=='data':m.segments[0].class_name='DATA'
   else:m.format='easy-omf-386'
   with self.subTest(kind=kind),self.assertRaises(MatchError):self.check(m,image)
 def test_zero_inline_addend_is_explicitly_required(self):
  for value in [1,0xffffffff]:
   m,image=self.fixture();m.segments[0].data[1:5]=value.to_bytes(4,'little')
   with self.subTest(value=value),self.assertRaisesRegex(MatchError,'frame'):self.check(m,image)
 def test_frame_is_exact_source_not_just_another_same_object_code_segment(self):
  m,image=self.fixture();m.segments.append(Segment('_OTHER','CODE',1,0x69,bytearray(b'\xc3')))
  m.fixups[0]=replace(m.fixups[0],frame=2)
  with self.assertRaisesRegex(MatchError,'frame'):self.check(m,image,placements={2:(1,16)})
 def test_source_placement_conflict_and_missing_external_reject(self):
  m,image=self.fixture()
  with self.assertRaisesRegex(MatchError,'placement'):self.check(m,image,placements={1:(1,0)})
  with self.assertRaisesRegex(MatchError,'unresolved external'):self.check(m,image,symbols={})
 def test_whole_source_frame_placement_must_fit_even_for_local_comparison(self):
  m,image=self.fixture();m.segments[0].size=100
  with self.assertRaisesRegex(MatchError,'frame'):self.check(m,image)
  m,image=self.fixture();m.segments[0].data=bytearray(4)+m.segments[0].data;m.segments[0].size=10
  m.fixups[0]=replace(m.fixups[0],offset=5);m.publics={'caller_':(1,4)}
  with self.assertRaisesRegex(MatchError,'frame'):
   compare_range(m,1,4,image,1,0,6,{'callee_':(1,24)})
 def test_cross_object_is_not_accepted_even_without_loader(self):
  m,image=self.fixture();image=copy.copy(image);image.objects=(*image.objects,replace(image.objects[0],base=0x20000))
  with self.assertRaises(MatchError):self.check(m,image,symbols={'callee_':(2,24)})
 def test_loader_on_same_object_relative_reference_rejects(self):
  for record in [b'\x07\0\x05\0\x01\x18\0',b'\x08\0\x05\0\x01\x18\0',b'\x17\0\x05\0\x01\x18\0']:
   m,image=self.fixture(record)
   with self.subTest(record=record.hex()),self.assertRaises(MatchError):self.check(m,image)
 def test_overlap_and_bounds_remain_checked(self):
  m,image=self.fixture();m.fixups.append(m.fixups[0])
  with self.assertRaisesRegex(MatchError,'overlap'):self.check(m,image)
  m,image=self.fixture();m.fixups[0]=replace(m.fixups[0],offset=4)
  with self.assertRaisesRegex(MatchError,'boundary'):self.check(m,image)
  m,image=self.fixture()
  with self.assertRaisesRegex(MatchError,'outside'):self.check(m,image,symbols={'callee_':(1,100)})
 def test_wrong_target_opcode_tail_and_annotation_bytes_are_not_masked(self):
  m,image=self.fixture();self.assertFalse(self.check(m,image,symbols={'callee_':(1,23)})['match'])
  for offset in [0,5]:
   m,image=self.fixture();m.code_data_ranges=[(1,0,6)];m.segments[0].data[offset]^=1
   with self.subTest(offset=offset):self.assertFalse(self.check(m,image)['match'])
 def test_existing_explicit_group_relative_path_remains_unchanged(self):
  m,image=self.fixture();m.groups=[('CGROUP',(1,))]
  m.fixups[0]=replace(m.fixups[0],frame_method=1,frame=1)
  r=compare_range(m,1,0,image,1,4,6,{'callee_':(1,24)},group_frames={1:(1,0)})
  self.assertTrue(r['match']);self.assertEqual(r['verified_fixups'],1)
 def test_existing_F5_FLAT_and_same_index_F0_remain_identical(self):
  expected=None
  for kind in ['new','F5','FLAT','F0sameindex']:
   m,image=self.fixture()
   if kind=='F5':m.fixups[0]=replace(m.fixups[0],frame_method=5,frame=None)
   elif kind=='FLAT':m.groups=[('FLAT',())];m.fixups[0]=replace(m.fixups[0],frame_method=1,frame=1)
   elif kind=='F0sameindex':
    m.segments.append(Segment('_OTHER','CODE',1,0x69,bytearray(b'\xc3')))
    m.fixups[0]=replace(m.fixups[0],frame=2,target_method=0,target=2)
   result=self.check(m,image,placements={2:(1,24)}if kind=='F0sameindex'else None)
   if expected is None:expected=result
   self.assertEqual(result,expected)

