"""Source-build and strictly prove the complete MACT CRC member.

The short table derives from the reflected CRC-16/IBM recurrence. Original
archive bytes are reference-only and never supply generated source/output.
"""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT),str(ROOT/'profiles/watcom/tools')]
from le import LEImage
from omf32 import Module
from runner import compile_source,compiler_bin
from tools.infer_bindings import infer_bindings
from tools.inventory_watcom_runtime import read_archive,select_member
from tools.preserve import TARGET_SHA256
from tools.prove_module import assert_contributions
from tools.verify_module import verify_module

OPTIONS = ['/5r','/s','/ort','/ol']
COMPILER_SHA256 = 'a4f4da1b8b2cd4e38b2b041975fc6b1d131255ae5eb575828b02f927fbf9bf65'
LIBRARY_SHA256 = '957cea0ffb125220dd156c74b61fed8328c3a54852cad3d892cf47bebab8f8db'
MEMBER = {'offset':94208,'size':1156,'name':'P:\\libMACT\\CRC.c',
          'sha256':'982c4ebb06a712c14620890e13651e12b3a49c3ecea3766f19add32f2acaef93'}
PUBLICS = {'UpdateCRC_':(1,0),'CalculateCRC_':(1,24),'_crc16tab':(4,0)}
PLACEMENTS = {1:(1,570880),4:(3,71184)}
EXPECTED = {'initialized_bytes':592,'zero_fill_bytes':0,'verified_fixups':2}


def digest_file(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def generate_table(polynomial=0xa001):
    """Eight reflected LSB-first steps for each possible input octet."""
    if not 0 < polynomial <= 0xffff or not polynomial & 1:
        raise ValueError('CRC polynomial must be an odd 16-bit value')
    table = []
    for index in range(256):
        value = index
        for _ in range(8):
            value = (value >> 1) ^ (polynomial if value & 1 else 0)
        table.append(value)
    return table


def render_table(values):
    if len(values) != 256 or any(not 0 <= value <= 0xffff for value in values):
        raise ValueError('CRC table must have exactly 256 unsigned16 values')
    # Signed short is intentional: UpdateCRC's native load sign-extends;
    # CalculateCRC explicitly converts each table element to unsigned short.
    signed = [value if value < 0x8000 else value-0x10000 for value in values]
    return ('/* Generated by tools/probe_mact_crc.py --generate-table.\n'
            ' * CRC-16/IBM: reflected polynomial 0xA001, eight LSB-first steps.\n'
            ' * These are mathematical short values, never target payload bytes.\n'
            ' */\nstatic short crc16tab[256] = {\n'
            + ''.join('    '+', '.join(str(v) for v in signed[i:i+8])+',\n' for i in range(0,256,8))
            + '};\n')


def expected_spec():
    return {'name':'MACT_CRC','source':'src/mact/crc.c','reference_headers':[],
            'overlay_headers':'src/mact','source_reference_evidence':'evidence/mact-crc-source-reference.json',
            'options':OPTIONS,'code_object':1,'code_offset':570880,
            'code_bytes':80,'code_publics':2,'expected':EXPECTED}


def load_spec():
    spec = json.loads((ROOT/'modules/mact_crc.json').read_text())
    if spec != expected_spec(): raise ValueError('changed measured CRC descriptor')
    return spec


def target_image():
    path = ROOT/'reference/DUKE3D.EXE'
    if path.stat().st_size != 1179131 or digest_file(path) != TARGET_SHA256:
        raise ValueError('target identity mismatch')
    return LEImage.parse(path.read_bytes())


def check_module(module,image,*,code_offset=570880,known=None,reference=False):
    inventory = [(s.name,s.class_name,s.size,s.attributes) for s in module.segments]
    if inventory != [('_TEXT','CODE',80,105),('CONST','DATA',0,169),
                     ('CONST2','DATA',0,169),('_DATA','DATA',512,169),
                     ('_BSS','BSS',0,105 if reference else 169)]:
        raise ValueError('changed native CRC segment geometry')
    if (module.publics != PUBLICS or module.local_publics != {'_crc16tab'} or
            module.externals != ['_crc16tab'] or module.local_externals != {1}):
        raise ValueError('changed CRC public/self-external scope or offsets')
    bound = infer_bindings(module,image,1,code_offset,known_symbols=known)
    proof = verify_module(module,image,bound['placements'],bound['symbols'])
    assert_contributions(proof,EXPECTED)
    if bound['placements'] != PLACEMENTS:
        raise ValueError('changed measured CRC placements')
    return bound,proof


def original_reference(image,raw=None):
    if raw is None: raw = (ROOT/'reference/duke3d-reconstructions/MACT386.LIB').read_bytes()
    archive = read_archive(raw)
    if archive['sha256'] != LIBRARY_SHA256:
        raise ValueError('original archive identity mismatch')
    member = select_member(raw,archive,MEMBER)
    module = Module.parse(raw[member['offset']:member['end']])
    bound,proof = check_module(module,image,reference=True)
    return {'library_sha256':LIBRARY_SHA256,'member':member,'placements':bound['placements'],
            'verification':proof,'reference_only':True,
            'scope':'Original full member reference only; zero rebuilt-source contribution credit'}


def prove(home,build):
    spec = load_spec()
    image = target_image()
    source = ROOT/spec['source']
    header = ROOT/'src/mact/crctable.h'
    identity = digest_file(source)
    header_identity = digest_file(header)
    compiler = home/compiler_bin(home)/'wcc386.exe'
    if digest_file(compiler) != COMPILER_SHA256:
        raise ValueError('pinned native compiler identity mismatch')
    if header.read_text() != render_table(generate_table()):
        raise ValueError('table source differs from mathematical recurrence')
    build.mkdir(parents=True,exist_ok=True)
    obj = build/'crc.obj'
    compile_source(home,source,obj,OPTIONS,30,include_dirs=[ROOT/'src/mact'])
    if (digest_file(source) != identity or digest_file(header) != header_identity or
            digest_file(compiler) != COMPILER_SHA256):
        raise ValueError('CRC input identity changed during native compilation')
    bound,proof = check_module(Module.parse(obj.read_bytes()),image)
    return {'kind':'complete source-built MACT CRC contribution, not a full executable',
            'target_sha256':TARGET_SHA256,'source':spec['source'],'source_sha256':identity,
            'headers_sha256':{'crctable.h':header_identity},
            'generator':'tools/probe_mact_crc.py','generator_sha256':digest_file(Path(__file__)),
            'compiler_sha256':COMPILER_SHA256,'options':OPTIONS,
            'descriptor':'modules/mact_crc.json','descriptor_sha256':digest_file(ROOT/'modules/mact_crc.json'),
            'native_object_sha256':digest_file(obj),'native_log_sha256':digest_file(obj.with_suffix('.log')),
            'placements':bound['placements'],'constraints':bound['constraints'],'verification':proof,
            'table_derivation':{'polynomial':0xa001,'direction':'reflected LSB-first','steps_per_entry':8,
                                'entries':256,'entry_bytes':2,'seed':0,'final_xor':0},
            'original_reference':original_reference(image),
            'source_code_bytes':80,'initialized_table_bytes':512,'new_complete_contributions':1,
            'scope':'Both native public CODE bodies including CalculateCRC tail, all mathematical table DATA, two fixups, and private table scope verify together. Empty BSS has no contribution.',
            'full_executable_rebuilt':False}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--home',type=Path,default=ROOT/'toolchains/watcom-10.0-ga')
    parser.add_argument('--build',type=Path)
    parser.add_argument('--report',type=Path,default=ROOT/'evidence/mact-crc-module.json')
    parser.add_argument('--generate-table',type=Path)
    args = parser.parse_args()
    if args.generate_table:
        args.generate_table.write_text(render_table(generate_table()))
        return
    if args.build is None: parser.error('--build is required for a native proof')
    report = prove(args.home.resolve(),args.build.resolve())
    args.report.write_text(json.dumps(report,indent=2)+'\n')
    print('MACT CRC source proof: 80 CODE + 512 mathematical DATA, 2 fixups, 0 BSS')


if __name__ == '__main__': main()
